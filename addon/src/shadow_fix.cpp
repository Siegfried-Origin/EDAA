// Lighting under the viewport jitter.
//
// Some lighting passes rebuild each pixel's position from the pixel's own
// coordinate and a view ray stored in a constant buffer, times the depth:
//   - the sun shadow mask (pixel shader 77cb0c225019d08b, fullscreen triangle):
//     SV_Position -> ndc -> ray = ndc.x * cb2[1] + ndc.y * cb2[2] + cb2[4];
//   - the tiled lighting of local lights (compute shaders 932e687ab8739aeb,
//     a6542bbe3011f87f, b499f7667d34932c, 083dc2646abe2d51): thread id ->
//     uv = (pixel + 0.5) / size -> ray.i = dot(cb0[10 + i].xyw, (u, v, 1));
//   - the ambient occlusion (compute shader 403797e056b7801d, HBAO+ style on
//     deinterleaved depth): view.xy = (uv * cb0[4].xy + cb0[4].zw) * z.
// The viewport offset jitters the depth but cannot move SV_Position or the
// thread ids, so positions are off by up to half a pixel along the depth
// slope and shadow tests flip on grazing surfaces, frame after frame (worst
// below 1x).
//
// For those draws and dispatches only, the bound constant buffer range is
// copied on the GPU, the ray is shifted by the jitter (shadow_fix.hlsl) and
// the copy is bound instead; the game's buffer is bound again before the next
// draw or dispatch if our copy is still bound there. Any unexpected state (no
// buffer, too small, no D3D11.1 context) leaves the call untouched. A game
// update changing a shader only changes its hash: the fix no longer applies.

#include "profile.hpp"
#include "events.hpp"
#include "state.hpp"

#include <algorithm>
#include <atomic>
#include <cstring>
#include <d3d11_1.h>
#include <mutex>
#include <wrl/client.h>

#include "shadow_shaders.h" // generated by fxc at build time

using Microsoft::WRL::ComPtr;
using namespace reshade::api;

