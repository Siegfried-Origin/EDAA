// GPU passes: camera motion vectors, TAA resolve and debug view.
//
// Resolve point (chosen in frame_tracking.cpp): right before the cockpit HUD
// pass, when the HDR scene target holds the finished world (fallback: right
// before the first bloom downsample). There:
//   1. motion pass: rebuild each pixel's camera-relative position from depth
//      (inverse of this frame's main viewProj, jitter removed), move it by the
//      camera position delta and project it with last frame's viewProj ->
//      RG16F motion (previous UV - current UV) + R8 vehicle mask (stencil bit
//      0x80 = player's vehicle, moves with the camera: zero motion);
//   2. TAA pass: current scene + reprojected history -> new history (RGBA16F);
//   3. copy pass: new history -> game's HDR scene target, consumed by the
//      game's HUD, bloom, tonemap, SMAA and downsample.
// At Present: optional debug view over the back buffer, then auto capture.
// Rendering uses D3D11 directly, with the game's state saved and restored.

